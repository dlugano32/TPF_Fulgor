"""Genera la LUT combinacional del cubo en GF(2^7).

Ejecutar desde la raiz del repositorio:
    python3 -m model.python.src.gf127_cube_lut_export
"""

from pathlib import Path

from model.python.tools.GF2m import GF2m


def cube_table_to_systemverilog(
    field: GF2m,
    input_name: str = "i_element",
    output_name: str = "o_cube",
) -> str:
    """Genera las 128 entradas; ZERO_CUBE configura la convencion en cero."""

    lines = [f"        case ({input_name})"]
    for element in range(field.order):
        cube = field.power(element, 3)
        cube_literal = "ZERO_CUBE" if element == 0 else f"7'h{cube:02X}"
        lines.append(
            f"            7'h{element:02X}: {output_name} = {cube_literal};"
        )
    lines.append(f"            default: {output_name} = 7'h00;")
    lines.append("        endcase")
    return "\n".join(lines) + "\n"


def write_gf127_cube_lut(output_directory: Path) -> Path:
    """Guarda el modulo completo en gf127_cube_lut.sv."""

    # p(x) = x^7 + x^3 + 1
    field = GF2m(m=7, primitive_poly=0b0001001)
    output_directory.mkdir(parents=True, exist_ok=True)
    cube_file = output_directory / "gf127_cube_lut.sv"
    header = """`timescale 1ps/1ps

// Generated by model/python/src/gf127_cube_lut_export.py.
// GF(2^7), p(x) = x^7 + x^3 + 1. By default, 0^3 = 0.
// ZERO_CUBE also supports the decoder's previous log(0)=0, exp(0)=1 convention.
module gf127_cube_lut #(
    parameter logic [6:0] ZERO_CUBE = 7'h00,
    localparam int M = 7
) (
    input  logic [M - 1 : 0] i_element,
    output logic [M - 1 : 0] o_cube
);
    always_comb begin : cube_lut
"""
    footer = """    end
endmodule
"""
    cube_file.write_text(
        header + cube_table_to_systemverilog(field) + footer,
        encoding="utf-8",
    )
    return cube_file


def main() -> None:
    output_directory = (
        Path(__file__).resolve().parents[3] / "rtl/rx/decoder/gf127_op"
    )
    cube_file = write_gf127_cube_lut(output_directory)
    print("Tabla cube:", cube_file)
    print("Entradas  : 128")


if __name__ == "__main__":
    main()
