interface prbs31_checker_if
    import prbs31_pkg::*;
#(
    localparam int CNT_W = $clog2(P + 1)
) (
    input logic clk
);
    logic                 i_rst_n;
    logic                 i_prbs_en;
    logic                 i_checker_en;
    logic [ORDER - 1 : 0] i_seed;
    logic [P - 1 : 0]     i_error_mask;

    logic [P - 1 : 0]     generated_data;         // Current registered PRBS output.
    logic [P - 1 : 0]     received_data;          // Current PRBS output after XOR injection.
    logic [P - 1 : 0]     checked_generated_data; // Preserves data generated by the prbs for posterior comparition
    logic [P - 1 : 0]     checked_received_data;  // Preserves data consumed by the checker for posterior comparition
    logic                 o_locked;
    logic [CNT_W - 1 : 0] o_error_count;

    // Synchronization scheme (the RTL samples and updates on posedge clk):
    //
    //   negedge N       : cb_mon samples the result of the previous posedge;
    //                     cb_drv then drives the next stimulus 1 ps later.
    //   following posedge: PRBS/checker consume that stimulus and update state.
    //   negedge N+1     : cb_mon samples those new RTL results.

    clocking cb_drv @(negedge clk);
        default input #1step output #1ps;
        output i_rst_n, i_prbs_en, i_checker_en, i_seed, i_error_mask;
    endclocking

    modport DRV (clocking cb_drv, input clk);

    clocking cb_mon @(negedge clk);
        default input #1step;
        input i_rst_n, i_checker_en;
        input checked_generated_data, checked_received_data;
        input o_locked, o_error_count;
    endclocking

    modport MON (clocking cb_mon, input clk);

endinterface
